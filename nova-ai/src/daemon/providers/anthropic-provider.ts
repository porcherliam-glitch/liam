// ModelProvider for the Anthropic Messages API (built-in factory "anthropic"): `POST {baseUrl}/v1/messages`,
// `GET {baseUrl}/v1/models`, headers `x-api-key` (or options.authHeader) and `anthropic-version: 2023-06-01`.
// Key decisions:
// - All system messages are joined into the top-level `system` field (JSON mode adds an instruction there because
//   the API has no response_format).
// - Tool results become user messages with `{type:"tool_result", tool_use_id, content}` blocks; consecutive
//   same-role messages are merged into one message with several content blocks (the API requires alternation), and
//   inside a merged user message tool_result blocks come first. Empty text blocks are dropped (the API rejects
//   them); a conversation that does not start with a user turn gets a short user "Continue." turn.
// - Tool-use ids are sanitised to the allowed alphabet ([A-Za-z0-9_-]) so ids generated by other providers work
//   after a fallback.
// - Usage: input_tokens (+ cache creation/read tokens, which are billed as input) and output_tokens.
// - Context length is not reported by the API; all Claude 3+ models have ≥ 200k tokens, so claude-* → 200000.
import type { ModelInfo, ProviderConfig, ProviderHealth } from '@shared/schemas';
import type { ChatMessage, ChatRequest, ChatResponse, ChatToolCall, ModelProvider, ProviderFactory, ProviderFactoryDeps } from '../contracts';
import { isLocalEndpoint } from '../core/net';
import { errorMessage } from '../core/errors';
import { invalidResponse, joinUrl, providerError, providerErrorDetails, requestJson, type HttpContext } from './http';
import { newToolCallId, toArgumentsObject } from './ollama-provider';

export const ANTHROPIC_VERSION = '2023-06-01';
const CHAT_SAFETY_TIMEOUT_MS = 60 * 60 * 1000;
const DEFAULT_MAX_TOKENS = 4096;

export type AnthropicBlock =
  | { type: 'text'; text: string }
  | { type: 'tool_use'; id: string; name: string; input: Record<string, unknown> }
  | { type: 'tool_result'; tool_use_id: string; content: string };

export interface AnthropicWireMessage {
  role: 'user' | 'assistant';
  content: AnthropicBlock[];
}

export function sanitizeToolId(id: string): string {
  const clean = id.replace(/[^A-Za-z0-9_-]/g, '_');
  return clean.length ? clean.slice(0, 200) : newToolCallId();
}

export function toAnthropicRequest(messages: ChatMessage[], json = false): { system: string | undefined; messages: AnthropicWireMessage[] } {
  const systemParts: string[] = [];
  const out: AnthropicWireMessage[] = [];
  for (const m of messages) {
    if (m.role === 'system') {
      if (m.content.trim()) systemParts.push(m.content);
      continue;
    }
    let role: 'user' | 'assistant';
    const blocks: AnthropicBlock[] = [];
    if (m.role === 'user') {
      role = 'user';
      if (m.content.trim()) blocks.push({ type: 'text', text: m.content });
    } else if (m.role === 'assistant') {
      role = 'assistant';
      if (m.content && m.content.trim()) blocks.push({ type: 'text', text: m.content });
      for (const tc of m.toolCalls ?? []) blocks.push({ type: 'tool_use', id: sanitizeToolId(tc.id), name: tc.name, input: tc.arguments ?? {} });
    } else {
      role = 'user';
      blocks.push({ type: 'tool_result', tool_use_id: sanitizeToolId(m.toolCallId), content: m.content.trim() ? m.content : '(no output)' });
    }
    if (!blocks.length) continue;
    const prev = out[out.length - 1];
    if (prev && prev.role === role) prev.content.push(...blocks);
    else out.push({ role, content: blocks });
  }
  for (const msg of out) {
    if (msg.role === 'user') msg.content.sort((a, b) => (a.type === 'tool_result' ? 0 : 1) - (b.type === 'tool_result' ? 0 : 1));
  }
  if (!out.length || out[0].role !== 'user') out.unshift({ role: 'user', content: [{ type: 'text', text: 'Continue.' }] });
  if (json) systemParts.push('Respond with exactly one JSON object and nothing else.');
  return { system: systemParts.length ? systemParts.join('\n\n') : undefined, messages: out };
}

export function fromAnthropicContent(content: unknown): { text: string; toolCalls: ChatToolCall[] } {
  let text = '';
  const toolCalls: ChatToolCall[] = [];
  if (Array.isArray(content)) {
    for (const block of content) {
      if (!block || typeof block !== 'object') continue;
      const b = block as { type?: unknown; text?: unknown; id?: unknown; name?: unknown; input?: unknown };
      if (b.type === 'text' && typeof b.text === 'string') text += b.text;
      else if (b.type === 'tool_use' && typeof b.name === 'string' && b.name) {
        toolCalls.push({ id: typeof b.id === 'string' && b.id ? b.id : newToolCallId(), name: b.name, arguments: toArgumentsObject(b.input) });
      }
    }
  }
  return { text, toolCalls };
}

class AnthropicProvider implements ModelProvider {
  readonly id: string;
  readonly type = 'anthropic' as const;
  private readonly ctx: HttpContext;
  private readonly root: string;

  constructor(
    private readonly cfg: ProviderConfig,
    private readonly deps: ProviderFactoryDeps,
  ) {
    this.id = cfg.id;
    this.ctx = { fetch: deps.fetch ?? fetch, label: cfg.name, family: 'cloud', providerId: cfg.id };
    this.root = cfg.baseUrl.replace(/\/+$/, '').replace(/\/v1$/, '');
  }

  config(): ProviderConfig {
    return { ...this.cfg, options: { ...this.cfg.options } };
  }

  private async headers(): Promise<Record<string, string> | null> {
    const key = await this.deps.getApiKey();
    if (!key && !isLocalEndpoint(this.cfg.baseUrl)) return null;
    const h: Record<string, string> = { 'anthropic-version': ANTHROPIC_VERSION };
    if (key) {
      const name = this.cfg.options.authHeader?.trim();
      h[name ? name : 'x-api-key'] = key;
    }
    return h;
  }

  private missingKey(): Error {
    return providerError('PROVIDER_AUTH', `Für „${this.cfg.name}“ ist kein API-Schlüssel hinterlegt. Bitte unter „Modelle“ einen Schlüssel eintragen.`, {
      providerId: this.id,
      requestSent: false,
      billable: false,
      retryable: false,
    });
  }

  async health(): Promise<ProviderHealth> {
    const started = Date.now();
    const headers = await this.headers();
    if (!headers) {
      return { providerId: this.id, status: 'not_configured', message: 'Kein API-Schlüssel hinterlegt.', version: null, checkedAt: Date.now(), latencyMs: null };
    }
    try {
      await requestJson(this.ctx, { method: 'GET', url: joinUrl(this.root, '/v1/models?limit=1'), headers, timeoutMs: 10_000 });
      return { providerId: this.id, status: 'ok', message: 'Verbunden.', version: ANTHROPIC_VERSION, checkedAt: Date.now(), latencyMs: Date.now() - started };
    } catch (e) {
      const d = providerErrorDetails(e);
      return {
        providerId: this.id,
        status: d?.status === 401 || d?.status === 403 ? 'auth_error' : d && !d.requestSent ? 'unreachable' : 'error',
        message: errorMessage(e),
        version: null,
        checkedAt: Date.now(),
        latencyMs: null,
      };
    }
  }

  async listModels(): Promise<ModelInfo[]> {
    const headers = await this.headers();
    if (!headers) throw this.missingKey();
    const local = isLocalEndpoint(this.cfg.baseUrl);
    const out: ModelInfo[] = [];
    let after: string | null = null;
    for (let page = 0; page < 10; page++) {
      const url = joinUrl(this.root, `/v1/models?limit=1000${after ? `&after_id=${encodeURIComponent(after)}` : ''}`);
      const { data } = await requestJson(this.ctx, { method: 'GET', url, headers, timeoutMs: 15_000 });
      const list = (data as { data?: unknown })?.data;
      if (!Array.isArray(list)) throw invalidResponse(this.ctx, 'Modellliste unlesbar');
      for (const item of list) {
        if (!item || typeof item !== 'object') continue;
        const raw = item as { id?: unknown; display_name?: unknown; created_at?: unknown };
        if (typeof raw.id !== 'string' || !raw.id) continue;
        const created = typeof raw.created_at === 'string' ? Date.parse(raw.created_at) : NaN;
        out.push({
          providerId: this.id,
          id: raw.id,
          displayName: typeof raw.display_name === 'string' && raw.display_name ? raw.display_name : raw.id,
          local,
          paid: this.cfg.paid,
          sizeBytes: null,
          parameterSize: null,
          quantization: null,
          family: 'claude',
          contextLength: raw.id.startsWith('claude-') ? 200_000 : null,
          capabilities: ['completion', 'tools', 'vision'],
          pricing: null,
          modifiedAt: Number.isNaN(created) ? null : created,
        });
      }
      const more = (data as { has_more?: unknown }).has_more === true;
      const last = (data as { last_id?: unknown }).last_id;
      if (!more || typeof last !== 'string') break;
      after = last;
    }
    return out;
  }

  async chat(req: ChatRequest): Promise<ChatResponse> {
    const headers = await this.headers();
    if (!headers) throw this.missingKey();
    const started = Date.now();
    const { system, messages } = toAnthropicRequest(req.messages, req.json);
    const body: Record<string, unknown> = { model: req.model, max_tokens: req.maxTokens ?? DEFAULT_MAX_TOKENS, messages };
    if (system) body.system = system;
    if (req.temperature !== undefined) body.temperature = Math.min(1, req.temperature);
    if (req.tools?.length) body.tools = req.tools.map((t) => ({ name: t.name, description: t.description, input_schema: t.parameters }));
    const { data } = await requestJson(this.ctx, {
      method: 'POST',
      url: joinUrl(this.root, '/v1/messages'),
      headers,
      body,
      signal: req.signal,
      timeoutMs: CHAT_SAFETY_TIMEOUT_MS,
      notFoundMessage: `${this.cfg.name}: Das Modell „${req.model}“ wurde nicht gefunden.`,
    });
    if (!data || typeof data !== 'object' || !Array.isArray((data as { content?: unknown }).content)) throw invalidResponse(this.ctx, 'Antwort ohne Inhalt');
    const d = data as { content: unknown[]; model?: unknown; stop_reason?: unknown; usage?: Record<string, unknown> };
    const { text, toolCalls } = fromAnthropicContent(d.content);
    const u = d.usage ?? {};
    const n = (v: unknown) => (typeof v === 'number' && Number.isFinite(v) ? v : 0);
    const reported = typeof u.input_tokens === 'number' && typeof u.output_tokens === 'number';
    return {
      content: text,
      toolCalls,
      usage: {
        inputTokens: n(u.input_tokens) + n(u.cache_creation_input_tokens) + n(u.cache_read_input_tokens),
        outputTokens: n(u.output_tokens),
        usageReported: reported,
      },
      durationMs: Date.now() - started,
      model: typeof d.model === 'string' ? d.model : req.model,
      finishReason: typeof d.stop_reason === 'string' ? d.stop_reason : null,
    };
  }
}

export const anthropicFactory: ProviderFactory = {
  type: 'anthropic',
  create(config: ProviderConfig, deps: ProviderFactoryDeps): ModelProvider {
    return new AnthropicProvider(config, deps);
  },
};
