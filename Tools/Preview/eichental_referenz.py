#!/usr/bin/env python3
"""Writes the reference values of the Python twin (eichental_layout.py) for the C# EditMode tests.

The C# classes in Assets/_Project/Scripts/World/Layout/ and eichental_layout.py must compute the same terrain, vegetation and
placements, otherwise the Blender preview would show something else than Unity builds. This script evaluates the real layout
with Python and writes Assets/_Project/Tests/EditModeWorld/EichentalPreviewReference.cs; the tests compare C# against it.

Run it after every change of eichental_layout.json (from the repo root):
    python3 -I Tools/Preview/eichental_referenz.py
"""
import collections
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import eichental_layout as L  # noqa: E402

LAYOUT = os.path.join(REPO, "Assets", "_Project", "Data", "Regions", "Eichental", "eichental_layout.json")
OUT = os.path.join(REPO, "Assets", "_Project", "Tests", "EditModeWorld", "EichentalPreviewReference.cs")

HEIGHT_POINTS = [(0.0, 0.0), (40.0, -30.0), (120.0, 44.0), (-152.0, 56.0), (-82.0, 186.0), (12.0, 184.0), (-2.0, 150.0),
                 (-128.0, -144.2), (250.0, 250.0), (-230.0, 10.0), (37.5, -117.25), (-112.4, 163.7), (180.0, -180.0)]


# Sample vertices of the rock meshes (icosphere levels 0, 1 and 2 are all represented).
ROCK_SAMPLE_VERTICES = [0, 5, 11, 12, 30, 41, 42, 100, 161]
BOULDER_SEEDS = [504, 517]  # 500 + 13 * variant + len("rock"), variants 0 and 1
BOULDER_SAMPLE_VERTICES = [0, 7, 11, 25, 41]


def r(value):
    return repr(float(value))


def main():
    layout = L.load(LAYOUT)
    hf = L.HeightField(layout)
    plants = L.scatter_vegetation(layout)
    counts = collections.OrderedDict()
    firsts = collections.OrderedDict()
    for p in plants:
        counts[p["group"]] = counts.get(p["group"], 0) + 1
        firsts.setdefault(p["group"], p)
    groups = [g["id"] for g in layout["vegetation"]["groups"]]

    lines = [
        "// <auto-generated>",
        "// Written by Tools/Preview/eichental_referenz.py from eichental_layout.json with the Python twin of the layout code.",
        "// Do not edit; run the script again after changing the layout.",
        "// </auto-generated>",
        "namespace Aetherfall.Tests.EditMode.World",
        "{",
        "    /// <summary>Reference values of the Python preview (Tools/Preview/eichental_layout.py) for the real Eichental layout.</summary>",
        "    public static class EichentalPreviewReference",
        "    {",
        "        /// <summary>Terrain height samples: x, z, height.</summary>",
        "        public static readonly object[] Heights =",
        "        {",
    ]
    for x, z in HEIGHT_POINTS:
        lines.append("            new object[] { %s, %s, %s }," % (r(x), r(z), r(hf.height(x, z))))
    lines += ["        };", "",
              "        /// <summary>Total number of plants (groups and landmark trees).</summary>",
              "        public const int PlantCount = %d;" % len(plants), "",
              "        /// <summary>Plants per scatter group: id, count.</summary>",
              "        public static readonly object[] GroupCounts =", "        {"]
    for g in groups:
        lines.append("            new object[] { \"%s\", %d }," % (g, counts.get(g, 0)))
    lines += ["        };", "",
              "        /// <summary>First plant per scatter group: id, kind (lower case), x, z, scale, yaw.</summary>",
              "        public static readonly object[] FirstPlants =", "        {"]
    for g in groups:
        if g in firsts:
            p = firsts[g]
            lines.append("            new object[] { \"%s\", \"%s\", %s, %s, %s, %s }," % (g, p["kind"], r(p["x"]), r(p["z"]), r(p["scale"]), r(p["yaw"])))
    lines += ["        };", "",
              "        /// <summary>Enemy positions: spawner id, index, x, z, yaw.</summary>",
              "        public static readonly object[] SpawnerPositions =", "        {"]
    for sp in layout["spawners"]:
        for i, (x, z, yaw) in enumerate(L.spawner_positions(sp)):
            lines.append("            new object[] { \"%s\", %d, %s, %s, %s }," % (sp["id"], i, r(x), r(z), r(yaw)))
    lines += ["        };", ""]
    crystals = L.rift_crystals(layout["rift"])
    lines += ["        /// <summary>Rift crystals: x, z, height, tilt x, tilt z, yaw.</summary>",
              "        public static readonly object[] Crystals =", "        {"]
    for c in crystals:
        lines.append("            new object[] { %s }," % ", ".join(r(v) for v in c))
    lines += ["        };", ""]
    lines += ["        /// <summary>Landmark rocks (RockGeometry.Landmark, render subdivisions): variant, vertices, triangles, sum x, sum y, sum z.</summary>",
              "        public static readonly object[] LandmarkRocks =", "        {"]
    for variant in range(3):
        verts, tris = L.rock_landmark(variant)
        sums = [sum(v[i] for v in verts) for i in range(3)]
        lines.append("            new object[] { %d, %d, %d, %s }," % (variant, len(verts), len(tris), ", ".join(r(x) for x in sums)))
    lines += ["        };", "",
              "        /// <summary>Sample vertices of the landmark rocks: variant, vertex index, x, y, z.</summary>",
              "        public static readonly object[] LandmarkRockVertices =", "        {"]
    for variant in range(3):
        verts, _ = L.rock_landmark(variant)
        for index in ROCK_SAMPLE_VERTICES:
            lines.append("            new object[] { %d, %d, %s }," % (variant, index, ", ".join(r(x) for x in verts[index])))
    lines += ["        };", "",
              "        /// <summary>Scattered boulders (RockGeometry.Boulder): seed, vertex index, x, y, z.</summary>",
              "        public static readonly object[] BoulderVertices =", "        {"]
    for seed in BOULDER_SEEDS:
        verts, _ = L.rock_boulder(seed)
        for index in BOULDER_SAMPLE_VERTICES:
            lines.append("            new object[] { %dUL, %d, %s }," % (seed, index, ", ".join(r(x) for x in verts[index])))
    lines += ["        };", ""]
    river_lines = []
    for index, river in enumerate(hf.rivers):
        for i, level in enumerate(river["levels"]):
            river_lines.append("            new object[] { %d, %d, %s }," % (index, i, r(level)))
    lines += ["        /// <summary>River water levels: river index, vertex, level.</summary>",
              "        public static readonly object[] RiverLevels =", "        {"] + river_lines + ["        };", "    }", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("OK", OUT, "-", len(plants), "Pflanzen,", len(HEIGHT_POINTS), "Höhenpunkte")


if __name__ == "__main__":
    main()
