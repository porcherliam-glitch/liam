namespace Aetherfall.World
{
    /// <summary>Plant or boulder of the vegetation (JSON <c>kind</c>).</summary>
    public enum VegetationKind
    {
        /// <summary><c>oak</c>: Oak (Eiche).</summary>
        Oak = 0,

        /// <summary><c>beech</c>: Beech (Buche).</summary>
        Beech = 1,

        /// <summary><c>birch</c>: Birch (Birke).</summary>
        Birch = 2,

        /// <summary><c>linden</c>: Large linden tree (Linde).</summary>
        Linden = 3,

        /// <summary><c>dead</c>: Burned, dead tree.</summary>
        Dead = 4,

        /// <summary><c>bush</c>: Bush (Strauch).</summary>
        Bush = 5,

        /// <summary><c>rock</c>: Boulder (Findling).</summary>
        Rock = 6
    }
}
