const byId = new Map(AREAS.map((a) => [a.id, a]))

export function areaDef(id: string): AreaDef {
  const a = byId.get(id)
  if (!a) throw new Error(`unknown area ${id}`)
  return a
}

/** An area is open when the level fits and (for later areas) a previous extraction unlocked it. */
export function areaUnlocked(area: AreaDef, level: number, unlockedAreas: string[]): boolean {
  if (level < area.unlockLevel) return false
  if (area.unlockAfter && !unlockedAreas.includes(area.id)) return false
  return true
}

/** Areas that open up after a successful extraction from `areaId`. */
export function areasUnlockedBy(areaId: string): string[] {
  return AREAS.filter((a) => a.unlockAfter === areaId).map((a) => a.id)
}
